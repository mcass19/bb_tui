defmodule BB.TUI.Extension.Info do
  @moduledoc """
  Reads a `BB.TUI.Extension` module's declarations.

  Generated by `Spark.InfoGenerator`: `drive_publish/1`, `drive_stop/1`,
  `drive_throttle_scale/1`, `drive_turn_scale/1` and `drive_rate/1` (each
  `{:ok, value} | :error`, with a `!` variant), and `panels/1`, `keys/1`
  and `hints/1` for the entity lists.
  """

  use Spark.InfoGenerator,
    extension: BB.TUI.Extension.Dsl,
    sections: [:drive, :panels, :keys, :hints]

  @doc """
  Whether `extension` declares a `drive`.
  """
  @spec drive?(module()) :: boolean()
  def drive?(extension), do: match?({:ok, _}, drive_publish(extension))
end
